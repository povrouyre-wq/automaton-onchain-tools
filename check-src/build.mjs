// Regenerates ../check-assets.js (bundled browser code for /check). Run: npm i -D esbuild && node check-src/build.mjs
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "fs";
import { createHash } from "crypto";
const here = new URL(".", import.meta.url).pathname;
const pay = (await build({ entryPoints: [here + "entry.js"], bundle: true, format: "esm", minify: true, target: "es2020", platform: "browser", write: false, legalComments: "none" })).outputFiles[0].text;
const ver = createHash("sha256").update(pay).digest("hex").slice(0, 12);
const app = (await build({ entryPoints: [here + "app.js"], bundle: false, minify: true, target: "es2020", write: false })).outputFiles[0].text.replace("__PAYVER__", ver);
writeFileSync(here + "../check-assets.js", `// GENERATED by check-src/build.mjs. Do not edit by hand.\nexport const PAY_VER = ${JSON.stringify(ver)};\nexport const APP_JS = ${JSON.stringify(app)};\nexport const PAY_JS = ${JSON.stringify(pay)};\n`);
console.log("pay", pay.length, "app", app.length, "ver", ver);
